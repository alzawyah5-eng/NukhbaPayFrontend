export function findCatalogueBrandImage(brand:string) {
 const pinned = catalogueLocalIcons.get(brand);
 if (pinned) return '/catalogue-logo-'+pinned;
 const value=brand.toLowerCase();
 const brands:[RegExp,string][]=[[/\bapple\b/,'apple.jpg'],[/google play/,'google_play.png'],[/\bsteam\b/,'steam.png'],
  [/playstation/,'playstation.png'],[/pubg/,'pubg.png'],[/^du(?: |$)/,'du.png'],[/^(?:e&|etisalat)/,'eand.png'],
  [/gcash/,'gcash.png'],[/salik/,'salik.png'],[/virgin mobile/,'virgin.png']];
 const match=brands.find(([pattern])=>pattern.test(value));
 return match?'/catalogue-logo-'+match[1]:undefined;
}
